-- ---------------------------------------------------------------------------
-- Discover — people
-- ---------------------------------------------------------------------------
-- Deterministic discovery only (no AI / engagement ranking): completed
-- profiles, not the viewer, not already followed, not blocked in either
-- direction, ranked by shared-interest overlap with the viewer then by
-- account age, with a stable final tie-break on id so pagination never skips
-- or repeats a row.

create function public.discover_people(
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id uuid,
  username text,
  display_name text,
  bio text,
  shared_interest_count integer,
  viewer_follows boolean,
  total_count bigint
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    p.id,
    p.username,
    p.display_name,
    p.bio,
    (
      select count(*)::integer
      from public.user_interests vi
      join public.user_interests ci
        on ci.interest_id = vi.interest_id and ci.user_id = p.id
      where vi.user_id = v_viewer
    ),
    -- Always false here: the WHERE clause below already excludes anyone the
    -- viewer follows. Included for a row shape uniform with search_people().
    false,
    count(*) over ()::bigint
  from public.profiles p
  where p.onboarding_completed
    and p.id <> v_viewer
    and not exists (
      select 1 from public.follows f
      where f.follower_id = v_viewer and f.following_id = p.id
    )
    and not public.blocked_between(v_viewer, p.id)
  order by
    (
      select count(*)::integer
      from public.user_interests vi
      join public.user_interests ci
        on ci.interest_id = vi.interest_id and ci.user_id = p.id
      where vi.user_id = v_viewer
    ) desc,
    p.created_at desc,
    p.id asc
  limit v_limit
  offset v_offset;
end;
$$;

-- ---------------------------------------------------------------------------
-- Discover — posts
-- ---------------------------------------------------------------------------
-- Recent PUBLIC posts only, block filtered, newest first, keyset paginated —
-- the exact same row shape as list_feed() so the application layer can reuse
-- its mapping and the existing PostFeed / PostCard components unchanged.

create function public.list_discover_posts(
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  user_id uuid,
  post_type text,
  body text,
  visibility text,
  created_at timestamptz,
  edited_at timestamptz,
  author_username text,
  author_display_name text,
  like_count integer,
  comment_count integer,
  viewer_liked boolean,
  viewer_bookmarked boolean,
  is_author boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    p.id,
    p.user_id,
    p.post_type,
    p.body,
    p.visibility,
    p.created_at,
    p.edited_at,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.post_likes pl where pl.post_id = p.id),
    (select count(*)::integer from public.post_comments pc
      where pc.post_id = p.id and pc.deleted_at is null),
    exists (
      select 1 from public.post_likes pl
      where pl.post_id = p.id and pl.user_id = v_viewer
    ),
    exists (
      select 1 from public.post_bookmarks pb
      where pb.post_id = p.id and pb.user_id = v_viewer
