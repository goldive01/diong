-- Attaches one already-uploaded Storage object to a post the caller owns.
-- Assumes the object itself was already ownership/type/size checked by the
-- Storage RLS policies and bucket config above; this RPC re-validates mime
-- type, size and the storage_path's expected prefix as the authoritative,
-- non-bypassable check (never trusts the client's claims alone), assigns the
-- next available position, and enforces the 4-image-per-post ceiling.
create function public.attach_post_media(
  p_post_id bigint,
  p_storage_path text,
  p_mime_type text,
  p_size_bytes bigint,
  p_width integer default null,
  p_height integer default null,
  p_alt_text text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_alt_text text := nullif(btrim(coalesce(p_alt_text, '')), '');
  v_expected_prefix text;
  v_next_position integer;
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.posts
    where id = p_post_id and user_id = v_viewer and deleted_at is null
  ) then
    raise exception using errcode = '42501', message = 'This post is not available.';
  end if;

  if p_mime_type is null or p_mime_type not in ('image/jpeg', 'image/png', 'image/webp') then
    raise exception using errcode = '22023', message = 'Choose a JPEG, PNG or WEBP image.';
  end if;

  if p_size_bytes is null or p_size_bytes <= 0 or p_size_bytes > 6291456 then
    raise exception using errcode = '22023', message = 'Image must be 6 MB or smaller.';
  end if;

  if v_alt_text is not null and char_length(v_alt_text) > 300 then
    raise exception using errcode = '22023', message = 'Alt text must be 300 characters or fewer.';
  end if;

  v_expected_prefix := 'posts/' || v_viewer::text || '/' || p_post_id::text || '/';
  if p_storage_path is null
     or char_length(p_storage_path) = 0
     or left(p_storage_path, char_length(v_expected_prefix)) <> v_expected_prefix
  then
    raise exception using errcode = '42501', message = 'This image cannot be attached.';
  end if;

  if (select count(*) from public.post_media where post_id = p_post_id) >= 4 then
    raise exception using errcode = '23514', message = 'A post can have at most 4 images.';
  end if;

  select coalesce(max(position) + 1, 0) into v_next_position
  from public.post_media where post_id = p_post_id;

  insert into public.post_media
    (post_id, user_id, storage_path, mime_type, size_bytes, width, height, position, alt_text)
  values
    (p_post_id, v_viewer, p_storage_path, p_mime_type, p_size_bytes, p_width, p_height, v_next_position, v_alt_text)
  returning id into v_new_id;

  return v_new_id;
end;
$$;

-- Removes one of the caller's own post_media rows and returns its
-- storage_path so the calling Server Action can delete the Storage object
-- after this DB write has succeeded.
create function public.remove_post_media(p_media_id bigint)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_storage_path text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  delete from public.post_media
  where id = p_media_id and user_id = v_viewer
  returning storage_path into v_storage_path;

  if not found then
    raise exception using errcode = '42501', message = 'This image is not available.';
  end if;

  return v_storage_path;
end;
$$;

-- Owner-only. p_storage_path = null removes the community avatar.
create function public.set_community_avatar(
  p_community_id bigint,
  p_storage_path text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_expected_prefix text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.communities where id = p_community_id and owner_id = v_viewer
  ) then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  if p_storage_path is not null then
    v_expected_prefix := 'communities/' || v_viewer::text || '/' || p_community_id::text || '/avatar/';
    if left(p_storage_path, char_length(v_expected_prefix)) <> v_expected_prefix then
      raise exception using errcode = '42501', message = 'This image cannot be used.';
    end if;
  end if;

  update public.communities
  set avatar_path = p_storage_path
  where id = p_community_id;
end;
$$;

