-- Case-insensitive substring match against name / slug / description, active
-- communities only. Same page-with-total shape as search_people().
create function public.search_communities(
  p_query text,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id bigint,
  slug text,
  name text,
  description text,
  member_count integer,
  viewer_joined boolean,
  total_count bigint
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_query text := btrim(coalesce(p_query, ''));
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_query) < 2 then
    return;
  end if;

  return query
  select
    c.id,
    c.slug,
    c.name,
    c.description,
    (select count(*)::integer from public.community_members m2 where m2.community_id = c.id),
    exists (
      select 1 from public.community_members m3
      where m3.community_id = c.id and m3.user_id = v_viewer
    ),
    count(*) over ()
  from public.communities c
  where c.is_active
    and (
      c.name ilike '%' || v_query || '%'
      or c.slug ilike '%' || v_query || '%'
      or c.description ilike '%' || v_query || '%'
    )
  order by (c.name ilike v_query || '%') desc, c.name asc, c.id asc
  limit v_limit offset v_offset;
end;
$$;

-- Members of a community, grouped by role rank (owner, moderator, member)
-- then join order, block-filtered, offset paginated. Only public profile
-- fields are returned — never email or auth metadata.
create function public.list_community_members(
  p_community_id bigint,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  user_id uuid,
  username text,
  display_name text,
  role text,
  joined_at timestamptz,
  total_count bigint
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.communities where id = p_community_id and is_active
  ) then
    return;
  end if;

  return query
  select
    m.user_id,
    pr.username,
    pr.display_name,
    m.role,
    m.joined_at,
    count(*) over ()
  from public.community_members m
  join public.profiles pr on pr.id = m.user_id
  where m.community_id = p_community_id
    and not public.blocked_between(v_viewer, m.user_id)
  order by
    case m.role when 'owner' then 0 when 'moderator' then 1 else 2 end,
    m.joined_at asc,
    m.user_id asc
  limit v_limit offset v_offset;
end;
$$;

-- Posts in a community, newest first, block-filtered, keyset paginated on
-- (created_at, id) — identical row shape to list_feed() / list_discover_posts()
-- / search_posts() so the application layer reuses the same mapping and
-- components. Only live (not removed) links on live (not deleted) posts.
create function public.list_community_posts(
  p_community_id bigint,
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  user_id uuid,
  post_type text,
  body text,
  visibility text,
  created_at timestamptz,
  edited_at timestamptz,
  author_username text,
  author_display_name text,
  like_count integer,
  comment_count integer,
  viewer_liked boolean,
  viewer_bookmarked boolean,
  is_author boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    p.id,
    p.user_id,
    p.post_type,
    p.body,
    p.visibility,
    p.created_at,
    p.edited_at,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.post_likes pl where pl.post_id = p.id),
    (select count(*)::integer from public.post_comments pc
      where pc.post_id = p.id and pc.deleted_at is null),
    exists (
      select 1 from public.post_likes pl
      where pl.post_id = p.id and pl.user_id = v_viewer
    ),
    exists (
      select 1 from public.post_bookmarks pb
      where pb.post_id = p.id and pb.user_id = v_viewer
    ),
    p.user_id = v_viewer
  from public.community_post_links l
  join public.posts p on p.id = l.post_id
  join public.profiles pr on pr.id = p.user_id
  where l.community_id = p_community_id
    and l.removed_at is null
    and p.deleted_at is null
    and not public.blocked_between(v_viewer, p.user_id)
    and (
      p_before_created_at is null
      or (p.created_at, p.id)
         < (p_before_created_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by p.created_at desc, p.id desc
  limit v_limit;
end;
$$;

-- Reports connected to one community: reports on the community itself, and
-- reports on any of its (not-removed) community posts. Owner/moderator only.
-- Never returns reporter_id — reporter identity is never exposed, even to
-- community moderators.
create function public.list_community_moderation_reports(p_community_id bigint)
returns table (
  id bigint,
  target_type text,
  target_id bigint,
  reason text,
  details text,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  -- coalesce guards against PL/pgSQL treating "NULL not in (...)" as false
  -- (branch skipped) for a caller who is not a member at all.
  if coalesce(public.community_role(p_community_id, v_viewer), 'none')
      not in ('owner', 'moderator') then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  return query
  select r.id, r.target_type, r.target_id, r.reason, r.details, r.status, r.created_at
  from public.reports r
  where
    (r.target_type = 'community' and r.target_id = p_community_id)
    or (
      r.target_type = 'community_post'
      and exists (
        select 1 from public.community_post_links l
        where l.community_id = p_community_id and l.post_id = r.target_id
      )
    )
  order by r.created_at desc, r.id desc
  limit 200;
end;
$$;

