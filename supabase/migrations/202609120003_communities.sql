revoke all on public.community_members from anon, authenticated;
revoke all on public.community_post_links from anon, authenticated;
revoke all on public.community_bans from anon, authenticated;
revoke all on public.reports from anon, authenticated;

-- Reads only, and only where a browser should ever see the row directly. All
-- writes go through a SECURITY DEFINER RPC below, matching the Pass 1–4
-- RPC-only model. community_bans and reports get NO select grant at all —
-- every read of those two tables happens inside a SECURITY DEFINER function
-- running as the function owner (bypassing RLS), exactly how
-- blocked_between() reads public.blocks today. This is what keeps a
-- moderator's ban list and report queue from ever needing a client-readable
-- policy, and keeps "browse other users' reports" impossible for anyone.
grant select on public.communities to authenticated;
grant select on public.community_members to authenticated;
grant select on public.community_post_links to authenticated;

-- Communities are PUBLIC in V1: any authenticated row is readable while active.
create policy "Read active communities"
on public.communities for select
to authenticated
using (is_active);

-- Member lists are public alongside their (active) community.
create policy "Read members of active communities"
on public.community_members for select
to authenticated
using (
  exists (
    select 1 from public.communities c
    where c.id = community_id and c.is_active
  )
);

-- A live (not removed) link on an active community is readable directly;
-- moderators see removed links through the dedicated moderation RPC instead
-- (SECURITY DEFINER, bypasses this policy), so removed posts do not need to
-- be exposed here.
create policy "Read live community post links"
on public.community_post_links for select
to authenticated
using (
  removed_at is null
  and exists (
    select 1 from public.communities c
    where c.id = community_id and c.is_active
  )
);

