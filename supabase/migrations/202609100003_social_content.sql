-- Diong Social Content — Social Network Pass 2: posts, feed, comments, likes,
-- bookmarks.
--
-- Additive only. Adds four tables (public.posts, public.post_comments,
-- public.post_likes, public.post_bookmarks), their RLS, two integrity triggers,
-- two internal helper functions and the SECURITY DEFINER RPCs that are the only
-- read path for the feed / detail / lists and the only write path for every
-- post, comment, like and bookmark mutation. Nothing in this file alters an
-- existing table, function, grant, policy or trigger. Daily Prime, Prime
-- history / reflections, Connections and the Pass 1 follow / block graph are
-- untouched.
--
-- Apply once, in order, after 202609100002_social_graph.sql. Depends on
-- public.profiles / auth.users (202607190001), public.follows / public.blocks
-- (202609100002) and public.set_updated_at() (202607190001). Each migration is a
-- single transaction and is NOT idempotent — never re-run a migration that
-- already succeeded.

