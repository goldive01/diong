-- Add a comment, or a reply to a top-level comment, on a post the caller can
-- see. A reply's parent must be a root comment on the same post (also enforced
-- by the enforce_comment_one_level trigger).
create function public.create_comment(
  p_post_id bigint,
  p_body text,
  p_parent_comment_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_body text := btrim(coalesce(p_body, ''));
  v_author uuid;
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 2000 then
    raise exception using errcode = '22023', message = 'Write between 1 and 2000 characters.';
  end if;

  if not public.viewer_can_see_post(p_post_id) then
    raise exception using errcode = '42501', message = 'This post is not available.';
  end if;

  select user_id into v_author from public.posts where id = p_post_id;
  if public.blocked_between(v_viewer, v_author) then
    raise exception using errcode = '42501', message = 'This post is not available.';
  end if;

  if p_parent_comment_id is not null then
    if not exists (
      select 1 from public.post_comments parent
      where parent.id = p_parent_comment_id
        and parent.post_id = p_post_id
        and parent.parent_comment_id is null
        and parent.deleted_at is null
    ) then
      raise exception using errcode = '22023', message = 'That comment can no longer be replied to.';
    end if;
  end if;

  insert into public.post_comments (post_id, user_id, parent_comment_id, body)
  values (p_post_id, v_viewer, p_parent_comment_id, v_body)
  returning id into v_new_id;

  return v_new_id;
end;
$$;

