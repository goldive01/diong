-- The viewer's inbox: one row per conversation that has at least one message,
-- most recently active first, block filtered (a conversation with either
-- account now blocking the other is hidden entirely, matching the Pass 3
-- notifications block policy). Keyset paginated on (last_message_at, id).
create function public.list_conversations(
  p_before_last_message_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  other_user_id uuid,
  other_username text,
  other_display_name text,
  last_message_body text,
  last_message_at timestamptz,
  unread boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    c.id,
    pr.id,
    pr.username,
    pr.display_name,
    lm.body,
    c.last_message_at,
    (
      lm.created_at is not null
      and lm.sender_id <> v_viewer
      and lm.created_at > coalesce(cm.last_read_at, '-infinity'::timestamptz)
    )
  from public.conversation_members cm
  join public.conversations c on c.id = cm.conversation_id
  join public.conversation_members other_cm
    on other_cm.conversation_id = c.id and other_cm.user_id <> v_viewer
  join public.profiles pr on pr.id = other_cm.user_id
  left join lateral (
    select m.body, m.created_at, m.sender_id
    from public.messages m
    where m.conversation_id = c.id
    order by m.created_at desc, m.id desc
    limit 1
  ) lm on true
  where cm.user_id = v_viewer
    and c.last_message_at is not null
    and not public.blocked_between(v_viewer, other_cm.user_id)
    and (
      p_before_last_message_at is null
      or (c.last_message_at, c.id)
         < (p_before_last_message_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by c.last_message_at desc, c.id desc
  limit v_limit;
end;
$$;

-- One conversation from the viewer's point of view, or no row when the
-- caller is not a member, the id does not exist, or a block now stands
-- between the two participants. The caller treats "no row" as notFound().
create function public.get_conversation(p_conversation_id bigint)
returns table (
  id bigint,
  other_user_id uuid,
  other_username text,
  other_display_name text,
  created_at timestamptz
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not public.is_conversation_member(p_conversation_id, v_viewer) then
    return;
  end if;

  return query
  select
    c.id,
    pr.id,
    pr.username,
    pr.display_name,
    c.created_at
  from public.conversations c
  join public.conversation_members cm
    on cm.conversation_id = c.id and cm.user_id <> v_viewer
  join public.profiles pr on pr.id = cm.user_id
  where c.id = p_conversation_id
    and not public.blocked_between(v_viewer, cm.user_id);
end;
$$;

-- Messages in one conversation, newest first, keyset paginated on
-- (created_at, id) — the same cursor shape as list_feed(). Returns nothing
-- when the caller is not a member or a block now stands between the two
-- participants, rather than raising, so a page can render an empty state.
create function public.list_messages(
  p_conversation_id bigint,
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  sender_id uuid,
  body text,
  created_at timestamptz,
  is_own boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_other uuid;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not public.is_conversation_member(p_conversation_id, v_viewer) then
    return;
  end if;

  select cm.user_id into v_other
  from public.conversation_members cm
  where cm.conversation_id = p_conversation_id and cm.user_id <> v_viewer;

  if v_other is not null and public.blocked_between(v_viewer, v_other) then
    return;
  end if;

  return query
  select
    m.id,
    m.sender_id,
    m.body,
    m.created_at,
    m.sender_id = v_viewer
  from public.messages m
  where m.conversation_id = p_conversation_id
    and (
      p_before_created_at is null
      or (m.created_at, m.id)
         < (p_before_created_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by m.created_at desc, m.id desc
  limit v_limit;
end;
$$;

-- Total unread message count across every non-blocked conversation the
-- viewer is a member of. Powers the Messages nav badge.
create function public.get_unread_message_count()
returns integer
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_count integer;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  select count(*)::integer into v_count
  from public.messages m
  join public.conversation_members cm
    on cm.conversation_id = m.conversation_id and cm.user_id = v_viewer
  join public.conversation_members other_cm
    on other_cm.conversation_id = m.conversation_id and other_cm.user_id <> v_viewer
  where m.sender_id <> v_viewer
    and m.created_at > coalesce(cm.last_read_at, '-infinity'::timestamptz)
    and not public.blocked_between(v_viewer, other_cm.user_id);

  return coalesce(v_count, 0);
end;
$$;

