-- Diong Communities — Social Network Pass 5: communities, membership,
-- moderation, bans and reporting.
--
-- Additive only. Adds five tables (public.communities, public.community_members,
-- public.community_post_links, public.community_bans, public.reports), their
-- RLS, two internal helper functions and the SECURITY DEFINER RPCs that are the
-- only read path for community / member / post / report lists and the only
-- write path for creating a community, joining/leaving, posting into a
-- community, moderation actions and reporting. Nothing in this file alters an
-- existing table, function, grant, policy or trigger. Daily Prime, Prime
-- history / reflections, Connections, the Pass 1 follow / block graph, the
-- Pass 2 post/comment/like/bookmark semantics, the Pass 3 Discover / Search
-- read paths and the Pass 4 direct-message model are untouched.
--
-- Apply once, in order, after 202609120002_direct_messages.sql. Depends on
-- public.profiles / auth.users (202607190001), public.follows / public.blocks
-- / public.blocked_between (202609100002 / 202609100003) and public.posts /
-- public.viewer_can_see_post (202609100003). Each migration is a single
-- transaction and is NOT idempotent — never re-run a migration that already
-- succeeded.
--
-- V1 design decision: communities are PUBLIC only. Any authenticated user
-- with a completed profile can read an active community, its member list and
-- its post feed. Membership is required only to create a community post.
-- Private / invite-only communities are deferred. There is no owner-transfer
-- feature in V1: the owner recorded at creation time can never leave and can
-- never be removed, demoted or banned by a moderator.
--
-- Community posts reuse the existing public.posts / post_comments /
-- post_likes / post_bookmarks system rather than forking a second post
-- ecosystem. A community post is always created with visibility = 'public'
-- and is linked via public.community_post_links. Moderator "removal" sets
-- removed_at/removed_by/removal_reason on the LINK row only — it removes the
-- post FROM THE COMMUNITY. The underlying public.posts row is never deleted
-- by community moderation; it continues to exist and remain visible through
-- normal Diong post visibility (feed, profile, direct link) unless its author
-- separately edits/soft-deletes it or platform moderation acts on it.
--
-- Reports schema deviation from the brief's literal field list: the brief's
-- suggested public.reports shape uses a single `target_id bigint`, which
-- fits post / comment / community / community_post targets (all bigint ids)
-- but not a `profile` target, whose id is a uuid (auth.users.id). Rather than
-- overload target_id with a text cast (which would defeat foreign-key-style
-- reasoning and make the CHECK constraints far less legible), this migration
-- adds one further nullable column, target_user_id uuid, used only for
-- target_type = 'profile'. This is additive to the brief, not a departure
-- from it, and is the same polymorphic-target idea Pass 3's notifications
-- table already uses (entity_type ties to exactly one entity_id shape) —
-- here a CHECK constraint ties target_type to exactly one of
-- (target_id, target_user_id) being set.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.communities (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  slug text not null unique,
  name text not null,
  description text not null default '',
  rules text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  is_active boolean not null default true,
  constraint communities_name_length check (char_length(btrim(name)) between 2 and 80),
  constraint communities_slug_format
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) between 3 and 60),
  constraint communities_description_length check (char_length(description) <= 2000),
  constraint communities_rules_length check (char_length(rules) <= 5000)
);

create table public.community_members (
  community_id bigint not null references public.communities(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null,
  joined_at timestamptz not null default now(),
  primary key (community_id, user_id),
  constraint community_members_role_allowed check (role in ('owner', 'moderator', 'member'))
);

-- One row per community post. post_id is unique — a post belongs to at most
-- one community. Moderator removal is recorded here (removed_at /
-- removed_by / removal_reason); the underlying post is never touched.
create table public.community_post_links (
  community_id bigint not null references public.communities(id) on delete cascade,
  post_id bigint not null unique references public.posts(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  removed_at timestamptz,
  removed_by uuid references auth.users(id) on delete set null,
  removal_reason text,
  constraint community_post_links_removal_reason_length
    check (removal_reason is null or char_length(removal_reason) <= 500),
  primary key (community_id, post_id)
);

-- Distinct from Diong's global user block (public.blocks). A community ban is
-- scoped to one community only and never affects the global follow/block
-- graph, direct messages, or any other community.
create table public.community_bans (
  community_id bigint not null references public.communities(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  banned_by uuid references auth.users(id) on delete set null,
  reason text,
  created_at timestamptz not null default now(),
  constraint community_bans_reason_length check (reason is null or char_length(reason) <= 500),
  primary key (community_id, user_id)
);

create table public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  target_type text not null,
  target_id bigint,
  target_user_id uuid references auth.users(id) on delete cascade,
  reason text not null,
  details text,
  status text not null default 'open',
  created_at timestamptz not null default now(),
  constraint reports_target_type_allowed check (target_type in (
    'post', 'comment', 'profile', 'community', 'community_post'
  )),
  constraint reports_reason_allowed check (reason in (
    'spam', 'harassment', 'hate_or_abuse', 'unsafe_content',
    'misinformation', 'impersonation', 'other'
  )),
  constraint reports_status_allowed check (status in (
    'open', 'reviewed', 'actioned', 'dismissed'
  )),
  constraint reports_details_length check (details is null or char_length(details) <= 2000),
  -- Exactly one target reference: target_user_id for a profile report,
  -- target_id (a bigint entity id) for every other target type.
  constraint reports_target_shape check (
    (target_type = 'profile' and target_user_id is not null and target_id is null)
    or (target_type <> 'profile' and target_id is not null and target_user_id is null)
  )
);

-- Practical duplicate-spam guard: one open report per (reporter, exact
-- target) at a time. A reporter may report the same target again once the
-- earlier report is reviewed/actioned/dismissed.
create unique index reports_reporter_target_open_unique_idx
  on public.reports (
    reporter_id,
    target_type,
    coalesce(target_id, -1),
    coalesce(target_user_id, '00000000-0000-0000-0000-000000000000'::uuid)
  )
  where status = 'open';

create index communities_slug_idx on public.communities (slug);
create index communities_created_idx on public.communities (created_at desc, id desc);

create index community_members_user_id_idx on public.community_members (user_id);
create index community_members_role_idx on public.community_members (community_id, role);

create index community_post_links_feed_idx
  on public.community_post_links (community_id, created_at desc);

create index community_bans_community_user_idx
  on public.community_bans (community_id, user_id);

create index reports_target_idx on public.reports (target_type, target_id);
create index reports_status_created_idx on public.reports (status, created_at desc);

create trigger communities_set_updated_at
before update on public.communities
for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Internal helper functions
-- ---------------------------------------------------------------------------
-- security definer, exactly like blocked_between() / is_conversation_member(),
-- so they can be used inside RLS policies and RPCs without recursion or an
-- extra client-facing grant on community_members / community_bans.

-- The caller's role in a community, or null if not a member.
create function public.community_role(p_community_id bigint, p_user_id uuid)
returns text
language sql
security definer
stable
set search_path = ''
as $$
  select role from public.community_members
  where community_id = p_community_id and user_id = p_user_id;
$$;

create function public.is_community_banned(p_community_id bigint, p_user_id uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.community_bans
    where community_id = p_community_id and user_id = p_user_id
  );
$$;

