create function public.complete_onboarding(
  p_username text,
  p_display_name text,
  p_bio text,
  p_interest_ids bigint[]
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  normalized_username text := lower(btrim(p_username));
  clean_display_name text := btrim(p_display_name);
  clean_bio text := nullif(btrim(p_bio), '');
  selected_count integer;
  valid_count integer;
begin
  if current_user_id is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if normalized_username !~ '^[a-z0-9_]{3,30}$' then
    raise exception using errcode = '22023', message = 'Username format is invalid.';
  end if;

  if char_length(clean_display_name) not between 1 and 60 then
    raise exception using errcode = '22023', message = 'Display name length is invalid.';
  end if;

  if clean_bio is not null and char_length(clean_bio) > 300 then
    raise exception using errcode = '22023', message = 'Bio is too long.';
  end if;

  select count(distinct interest_id)::integer
  into selected_count
  from unnest(coalesce(p_interest_ids, '{}'::bigint[])) as interest_id;

  if selected_count not between 1 and 5
     or selected_count <> coalesce(array_length(p_interest_ids, 1), 0) then
    raise exception using errcode = '22023', message = 'Choose between 1 and 5 unique interests.';
  end if;

  select count(*)::integer
  into valid_count
  from public.interests
  where id = any(p_interest_ids) and is_active;

  if valid_count <> selected_count then
    raise exception using errcode = '22023', message = 'One or more interests are invalid or inactive.';
  end if;

  insert into public.profiles (id)
  values (current_user_id)
  on conflict (id) do nothing;

  update public.profiles
  set username = normalized_username,
      display_name = clean_display_name,
      bio = clean_bio,
      onboarding_completed = false
  where id = current_user_id;

  delete from public.user_interests where user_id = current_user_id;

  insert into public.user_interests (user_id, interest_id)
  select current_user_id, interest_id
  from unnest(p_interest_ids) as interest_id;

  update public.profiles
  set onboarding_completed = true
  where id = current_user_id;

  if not found then
    raise exception using errcode = 'P0001', message = 'Profile could not be completed.';
  end if;
end;
$$;

revoke all on function public.complete_onboarding(text, text, text, bigint[]) from public, anon;
