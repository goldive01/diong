-- Owner or moderator. Neither may ever target the owner. A moderator may
-- only remove a plain member — never another moderator; only the owner
-- manages moderators (promote/demote/remove).
create function public.remove_community_member(p_community_id bigint, p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_caller_role text;
  v_target_role text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  v_caller_role := public.community_role(p_community_id, v_viewer);
  -- coalesce guards against PL/pgSQL treating "NULL not in (...)" as false
  -- (branch skipped) for a caller who is not a member at all.
  if coalesce(v_caller_role, 'none') not in ('owner', 'moderator') then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  v_target_role := public.community_role(p_community_id, p_user_id);
  if v_target_role is null then
    raise exception using errcode = '42501', message = 'That member is not available.';
  end if;
  if v_target_role = 'owner' then
    raise exception using errcode = '42501', message = 'The owner cannot be removed.';
  end if;
  if v_caller_role = 'moderator' and v_target_role = 'moderator' then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  delete from public.community_members
  where community_id = p_community_id and user_id = p_user_id;
end;
$$;

-- Owner or moderator. Same never-the-owner / moderator-cannot-target-moderator
-- rule as remove_community_member. Removes membership and records the ban.
create function public.ban_community_member(
  p_community_id bigint,
  p_user_id uuid,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_caller_role text;
  v_target_role text;
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  v_caller_role := public.community_role(p_community_id, v_viewer);
  -- coalesce guards against PL/pgSQL treating "NULL not in (...)" as false
  -- (branch skipped) for a caller who is not a member at all.
  if coalesce(v_caller_role, 'none') not in ('owner', 'moderator') then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  v_target_role := public.community_role(p_community_id, p_user_id);
  if v_target_role = 'owner' then
    raise exception using errcode = '42501', message = 'The owner cannot be banned.';
  end if;
  if v_caller_role = 'moderator' and v_target_role = 'moderator' then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  if v_reason is not null and char_length(v_reason) > 500 then
    raise exception using errcode = '22023', message = 'Reason must be 500 characters or fewer.';
  end if;

  delete from public.community_members
  where community_id = p_community_id and user_id = p_user_id;

  insert into public.community_bans (community_id, user_id, banned_by, reason)
  values (p_community_id, p_user_id, v_viewer, v_reason)
  on conflict (community_id, user_id) do nothing;
end;
$$;

-- Owner or moderator. Unbanning does NOT recreate membership — the user may
-- join again through the normal join_community path.
create function public.unban_community_member(p_community_id bigint, p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
