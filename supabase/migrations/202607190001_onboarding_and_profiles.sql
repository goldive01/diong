begin;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  bio text,
  avatar_url text,
  onboarding_completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_required_when_complete
    check (not onboarding_completed or username is not null),
  constraint profiles_display_name_required_when_complete
    check (not onboarding_completed or display_name is not null),
  constraint profiles_username_format
    check (
      username is null or (
        username = lower(username)
        and char_length(username) between 3 and 30
        and username ~ '^[a-z0-9_]+$'
      )
    ),
  constraint profiles_display_name_length
    check (display_name is null or char_length(btrim(display_name)) between 1 and 60),
  constraint profiles_bio_length
    check (bio is null or char_length(bio) <= 300)
);

create table public.interests (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text unique not null,
  description text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.user_interests (
  user_id uuid not null references auth.users(id) on delete cascade,
  interest_id bigint not null references public.interests(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, interest_id)
);

-- The username unique constraint already supplies the username lookup index.
create index interests_active_order_idx on public.interests (sort_order, id)
  where is_active;
create index user_interests_interest_id_idx on public.user_interests (interest_id);

