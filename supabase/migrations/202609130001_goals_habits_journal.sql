create trigger goals_set_updated_at
before update on public.goals
for each row execute function public.set_updated_at();

-- Keeps completed_at / progress_percent consistent with a status change in
-- the same statement: entering 'completed' stamps completed_at and forces
-- progress_percent to 100 (satisfying goals_completed_progress_full without
-- requiring the caller to also send progress_percent); leaving 'completed'
-- (a reopen) clears completed_at. progress_percent is left as-is on reopen —
-- nothing in the brief asks for it to reset, and the owner can call
-- setGoalProgress again once the goal is no longer 'completed'.
create function public.apply_goal_completion_status()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'completed' and old.status is distinct from 'completed' then
    new.completed_at := now();
    new.progress_percent := 100;
  elsif new.status <> 'completed' and old.status = 'completed' then
    new.completed_at := null;
  end if;
  return new;
end;
$$;

create trigger goals_apply_completion_status
before update on public.goals
for each row execute function public.apply_goal_completion_status();

create trigger habits_set_updated_at
before update on public.habits
for each row execute function public.set_updated_at();

-- Keeps archived_at consistent with is_active in the same statement, the
-- same "derived column excluded from every grant" pattern
-- connections.last_meaningful_contact_at uses (there via an RPC; here via a
-- trigger, since flipping is_active is a plain column update with no other
-- side effect to coordinate).
create function public.apply_habit_archived_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.is_active = false and old.is_active = true then
    new.archived_at := now();
  elsif new.is_active = true and old.is_active = false then
    new.archived_at := null;
  end if;
  return new;
end;
$$;

create trigger habits_apply_archived_at
before update on public.habits
for each row execute function public.apply_habit_archived_at();

create trigger journal_entries_set_updated_at
before update on public.journal_entries
for each row execute function public.set_updated_at();

-- Same-owner integrity for journal_entries' three optional cross-links.
-- security definer so the existence checks are not themselves subject to
-- goals/habits/prime_assignments RLS from inside the trigger — the check is
-- against new.user_id either way, so this only ever confirms what RLS would
-- already imply, never widens what a caller can see.
create function public.enforce_journal_entry_ownership()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.goal_id is not null and not exists (
    select 1 from public.goals where id = new.goal_id and user_id = new.user_id
  ) then
    raise exception using errcode = '42501', message = 'That goal is not available.';
  end if;

  if new.habit_id is not null and not exists (
    select 1 from public.habits where id = new.habit_id and user_id = new.user_id
  ) then
    raise exception using errcode = '42501', message = 'That habit is not available.';
  end if;

  if new.prime_assignment_id is not null and not exists (
    select 1 from public.prime_assignments
    where id = new.prime_assignment_id and user_id = new.user_id
  ) then
    raise exception using errcode = '42501', message = 'That Daily Prime is not available.';
  end if;

  return new;
end;
$$;

create trigger journal_entries_enforce_ownership
before insert or update on public.journal_entries
for each row execute function public.enforce_journal_entry_ownership();

revoke all on function public.apply_goal_completion_status() from public, anon, authenticated;
revoke all on function public.apply_habit_archived_at() from public, anon, authenticated;
revoke all on function public.enforce_journal_entry_ownership() from public, anon, authenticated;

