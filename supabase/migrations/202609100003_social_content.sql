-- ---------------------------------------------------------------------------
-- Integrity triggers (defence in depth)
-- ---------------------------------------------------------------------------
-- The RPCs below are the only write path in the application, but these triggers
-- keep the comment-depth invariant true no matter how a row is inserted.

create function public.enforce_comment_one_level()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.parent_comment_id is not null then
    if not exists (
      select 1
      from public.post_comments parent
      where parent.id = new.parent_comment_id
        and parent.post_id = new.post_id
        and parent.parent_comment_id is null
    ) then
      raise exception using errcode = '22023',
        message = 'A reply must point at a top-level comment on the same post.';
    end if;
  end if;
  return new;
end;
$$;

create trigger post_comments_enforce_one_level
before insert on public.post_comments
for each row execute function public.enforce_comment_one_level();

create trigger post_comments_set_updated_at
before update on public.post_comments
for each row execute function public.set_updated_at();

create trigger posts_set_updated_at
before update on public.posts
for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Internal helper functions
-- ---------------------------------------------------------------------------
-- Both are SECURITY DEFINER because they read public.blocks, which a client can
-- only read where it is the blocker. They are used by the RLS policies and the
-- RPCs; EXECUTE is granted to authenticated (each returns only a boolean about
-- the calling user's own relationship to one other account / post).

-- Is there a block in either direction between the two users?
create function public.blocked_between(p_a uuid, p_b uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.blocks
    where (blocker_id = p_a and blocked_id = p_b)
       or (blocker_id = p_b and blocked_id = p_a)
  );
$$;

-- Can the current user (auth.uid()) see this post? Encapsulates the full
-- visibility model: a live (non-deleted) post is visible to its author always;
-- to everyone else only when no block stands between them and the author AND
-- the post is public, or followers-only and they follow the author. Private
-- posts are visible to the author alone.
create function public.viewer_can_see_post(p_post_id bigint)
returns boolean
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_post public.posts;
begin
  if v_viewer is null then
    return false;
  end if;

  select * into v_post from public.posts where id = p_post_id;
  if not found or v_post.deleted_at is not null then
    return false;
  end if;

  if v_post.user_id = v_viewer then
    return true;
  end if;

  if public.blocked_between(v_viewer, v_post.user_id) then
    return false;
  end if;

  if v_post.visibility = 'public' then
    return true;
  end if;

  if v_post.visibility = 'followers' then
    return exists (
      select 1 from public.follows
      where follower_id = v_viewer and following_id = v_post.user_id
    );
  end if;

  return false;
end;
$$;

