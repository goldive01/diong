create function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create function public.validate_profile_completion()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  selected_count integer;
begin
  if new.onboarding_completed then
    select count(*)::integer
    into selected_count
    from public.user_interests
    join public.interests on interests.id = user_interests.interest_id
    where user_interests.user_id = new.id
      and interests.is_active;

    if selected_count not between 1 and 5 then
      raise exception using
        errcode = '23514',
        message = 'Completed onboarding requires between 1 and 5 active interests.';
    end if;
  end if;

  return new;
end;
$$;

create trigger profiles_validate_completion
before insert or update of onboarding_completed on public.profiles
for each row execute function public.validate_profile_completion();

create function public.validate_completed_user_interest_count()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  affected_user_id uuid := coalesce(new.user_id, old.user_id);
  profile_is_complete boolean;
  selected_count integer;
begin
  select onboarding_completed
  into profile_is_complete
  from public.profiles
  where id = affected_user_id;

  if profile_is_complete then
    select count(*)::integer
    into selected_count
    from public.user_interests
    join public.interests on interests.id = user_interests.interest_id
    where user_interests.user_id = affected_user_id
      and interests.is_active;

    if selected_count not between 1 and 5 then
      raise exception using
        errcode = '23514',
        message = 'Completed onboarding requires between 1 and 5 active interests.';
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create constraint trigger user_interests_validate_completed_count
after insert or delete on public.user_interests
deferrable initially immediate
for each row execute function public.validate_completed_user_interest_count();

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  safe_display_name text;
begin
  safe_display_name := btrim(new.raw_user_meta_data ->> 'display_name');

  if safe_display_name is null or char_length(safe_display_name) not between 1 and 60 then
    safe_display_name := null;
  end if;

  insert into public.profiles (id, display_name)
  values (new.id, safe_display_name)
  on conflict (id) do nothing;

  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

