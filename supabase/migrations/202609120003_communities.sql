-- Creates a community and inserts the creator as its owner member, atomically.
-- owner_id is always auth.uid() — never a client-supplied column.
create function public.create_community(
  p_name text,
  p_slug text,
  p_description text default '',
  p_rules text default ''
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_name text := btrim(coalesce(p_name, ''));
  v_slug text := lower(btrim(coalesce(p_slug, '')));
  v_description text := btrim(coalesce(p_description, ''));
  v_rules text := btrim(coalesce(p_rules, ''));
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.profiles where id = v_viewer and onboarding_completed
  ) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  if char_length(v_name) < 2 or char_length(v_name) > 80 then
    raise exception using errcode = '22023', message = 'Choose a name between 2 and 80 characters.';
  end if;

  if v_slug !~ '^[a-z0-9]+(-[a-z0-9]+)*$' or char_length(v_slug) < 3 or char_length(v_slug) > 60 then
    raise exception using errcode = '22023', message = 'Choose a valid slug.';
  end if;

  if char_length(v_description) > 2000 then
    raise exception using errcode = '22023', message = 'Description must be 2000 characters or fewer.';
  end if;

  if char_length(v_rules) > 5000 then
    raise exception using errcode = '22023', message = 'Rules must be 5000 characters or fewer.';
  end if;

  if exists (select 1 from public.communities where slug = v_slug) then
    raise exception using errcode = '23505', message = 'That slug is already taken.';
  end if;

  insert into public.communities (owner_id, slug, name, description, rules)
  values (v_viewer, v_slug, v_name, v_description, v_rules)
  returning id into v_new_id;

  insert into public.community_members (community_id, user_id, role)
  values (v_new_id, v_viewer, 'owner');

  return v_new_id;
end;
$$;

-- Join an active community. Idempotent (on conflict do nothing). Rejects a
-- banned caller before checking existing membership.
create function public.join_community(p_community_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.profiles where id = v_viewer and onboarding_completed
  ) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  if not exists (
    select 1 from public.communities where id = p_community_id and is_active
  ) then
    raise exception using errcode = '42501', message = 'This community is not available.';
  end if;

  if public.is_community_banned(p_community_id, v_viewer) then
    raise exception using errcode = '42501', message = 'You cannot join this community.';
  end if;

  insert into public.community_members (community_id, user_id, role)
  values (p_community_id, v_viewer, 'member')
  on conflict (community_id, user_id) do nothing;
end;
$$;

-- Leave a community. A no-op (not an error) for a caller who is not a
-- member. The owner can never leave in V1 (no ownership transfer) — this is
-- rejected with a safe, specific message rather than the generic
-- not_available case.
create function public.leave_community(p_community_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if exists (
    select 1 from public.communities where id = p_community_id and owner_id = v_viewer
  ) then
    raise exception using errcode = '42501',
      message = 'Community owners cannot leave their community.';
  end if;

  delete from public.community_members
  where community_id = p_community_id and user_id = v_viewer;
end;
$$;

-- Creates a normal Diong post (always visibility = 'public') and links it to
-- the community in one atomic function body. Requires live membership, no
-- ban, and an active community — re-checked here even though join_community
-- already screens membership, since a ban can be applied after joining.
create function public.create_community_post(
  p_community_id bigint,
  p_post_type text,
  p_body text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_body text := btrim(coalesce(p_body, ''));
  v_post_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.communities where id = p_community_id and is_active
  ) then
    raise exception using errcode = '42501', message = 'This community is not available.';
  end if;

  if public.is_community_banned(p_community_id, v_viewer) then
    raise exception using errcode = '42501', message = 'You cannot post in this community.';
  end if;

  if public.community_role(p_community_id, v_viewer) is null then
    raise exception using errcode = '42501', message = 'Join this community to post.';
  end if;

  if p_post_type is null or p_post_type not in (
    'update', 'reflection', 'progress', 'learning', 'achievement', 'question', 'resource'
  ) then
    raise exception using errcode = '22023', message = 'Choose a valid post type.';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 5000 then
    raise exception using errcode = '22023', message = 'Write between 1 and 5000 characters.';
  end if;

  insert into public.posts (user_id, post_type, body, visibility)
  values (v_viewer, p_post_type, v_body, 'public')
  returning id into v_post_id;

  insert into public.community_post_links (community_id, post_id, author_id)
  values (p_community_id, v_post_id, v_viewer);

  return v_post_id;
end;
$$;

-- Removes a post FROM THE COMMUNITY only: stamps the link row. The
-- underlying public.posts row is never modified or deleted here, so the
-- author's post keeps its normal Diong visibility. Owner or moderator only.
create function public.remove_community_post(
  p_community_id bigint,
  p_post_id bigint,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  v_role text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  v_role := public.community_role(p_community_id, v_viewer);
  -- coalesce is required: for a non-member v_role is NULL, and "NULL not in
  -- (...)" evaluates to NULL, which PL/pgSQL's IF treats as false (branch
  -- skipped) — without the coalesce a non-member would silently bypass this
  -- authorization check entirely.
  if coalesce(v_role, 'none') not in ('owner', 'moderator') then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  if v_reason is not null and char_length(v_reason) > 500 then
    raise exception using errcode = '22023', message = 'Reason must be 500 characters or fewer.';
  end if;

  update public.community_post_links
  set removed_at = now(), removed_by = v_viewer, removal_reason = v_reason
  where community_id = p_community_id and post_id = p_post_id and removed_at is null;

  if not found then
    raise exception using errcode = '42501', message = 'This community post is not available.';
  end if;
end;
$$;

-- Owner-only. Promotes an existing plain member to moderator. Never operates
-- on the owner (who already holds 'owner' and is excluded by the role check).
create function public.promote_community_moderator(p_community_id bigint, p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.communities where id = p_community_id and owner_id = v_viewer
  ) then
    raise exception using errcode = '42501', message = 'You are not authorized to do that.';
  end if;

  update public.community_members
  set role = 'moderator'
  where community_id = p_community_id and user_id = p_user_id and role = 'member';

  if not found then
    raise exception using errcode = '42501', message = 'That member is not available.';
  end if;
end;
$$;

