end;
$$;

-- Creates a report. reporter_id is always auth.uid(). Silently succeeds (no
-- new row, no error) on a duplicate open report against the same target, so
-- the caller never learns whether their report was the first — the same
-- "never reveal what moderation will do" policy the brief asks for.
create function public.create_report(
  p_target_type text,
  p_target_id bigint,
  p_target_user_id uuid,
  p_reason text,
  p_details text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_details text := nullif(btrim(coalesce(p_details, '')), '');
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.profiles where id = v_viewer and onboarding_completed
  ) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  if p_target_type is null or p_target_type not in (
    'post', 'comment', 'profile', 'community', 'community_post'
  ) then
    raise exception using errcode = '22023', message = 'Choose a valid report target.';
  end if;

  if p_reason is null or p_reason not in (
    'spam', 'harassment', 'hate_or_abuse', 'unsafe_content',
    'misinformation', 'impersonation', 'other'
  ) then
    raise exception using errcode = '22023', message = 'Choose a valid reason.';
  end if;

  if v_details is not null and char_length(v_details) > 2000 then
    raise exception using errcode = '22023', message = 'Details must be 2000 characters or fewer.';
  end if;

  if p_target_type = 'profile' then
    if p_target_user_id is null or p_target_id is not null then
      raise exception using errcode = '22023', message = 'Choose a valid report target.';
    end if;
    if p_target_user_id = v_viewer then
      raise exception using errcode = '22023', message = 'You cannot report your own profile.';
    end if;
    if not exists (
      select 1 from public.profiles where id = p_target_user_id and onboarding_completed
    ) then
      raise exception using errcode = '42501', message = 'This account is not available.';
    end if;
  else
    if p_target_id is null or p_target_user_id is not null then
      raise exception using errcode = '22023', message = 'Choose a valid report target.';
    end if;

    if p_target_type = 'post' and not public.viewer_can_see_post(p_target_id) then
      raise exception using errcode = '42501', message = 'This post is not available.';
    end if;

    if p_target_type = 'comment' and not exists (
      select 1 from public.post_comments c
      where c.id = p_target_id
        and c.deleted_at is null
        and public.viewer_can_see_post(c.post_id)
    ) then
      raise exception using errcode = '42501', message = 'This comment is not available.';
    end if;

    if p_target_type = 'community' and not exists (
      select 1 from public.communities where id = p_target_id and is_active
    ) then
      raise exception using errcode = '42501', message = 'This community is not available.';
    end if;

    if p_target_type = 'community_post' and not exists (
      select 1 from public.community_post_links l
      join public.communities c on c.id = l.community_id
      where l.post_id = p_target_id and l.removed_at is null and c.is_active
    ) then
      raise exception using errcode = '42501', message = 'This community post is not available.';
    end if;
  end if;

  insert into public.reports
    (reporter_id, target_type, target_id, target_user_id, reason, details)
  values
    (v_viewer, p_target_type, p_target_id, p_target_user_id, p_reason, v_details)
  on conflict (
    reporter_id, target_type, coalesce(target_id, -1),
    coalesce(target_user_id, '00000000-0000-0000-0000-000000000000'::uuid)
  )
  where status = 'open'
  do nothing;
end;
$$;

