-- Diong Personal Development — Pass 6: Goals, Habits and a Private Journal.
--
-- Additive only. Adds five tables (public.goals, public.goal_milestones,
-- public.habits, public.habit_checkins, public.journal_entries), their
-- indexes, RLS, five triggers and four SECURITY DEFINER RPCs. Nothing in
-- this file alters an existing table, function, grant, policy or trigger.
-- Daily Prime, Connections, the social graph, posts/feed, notifications,
-- Discover/Search, direct messages and communities are untouched.
--
-- Apply once, in order, after 202609120003_communities.sql. Depends on
-- public.profiles / auth.users (202607190001) and public.prime_assignments
-- (202607270001) for the journal's optional Daily Prime link. Each migration
-- is a single transaction and is NOT idempotent — never re-run a migration
-- that already succeeded.
--
-- Privacy: every table here is strictly owner-only. There is no shared,
-- public or cross-user select policy anywhere in this file. None of this
-- data is ever surfaced by the feed, Discover, Search, public profiles,
-- communities, messages, or notifications sent to other users.
--
-- Architecture decision (mirrors the Connections Phase A/B split): goals,
-- habits and journal_entries are plain owner-CRUD tables with column-scoped,
-- revoke-first grants — the same model public.connections already uses.
-- goal_milestones and habit_checkins are the "child" tables (one goal has
-- many milestones; one habit has many check-ins) and follow the
-- connection_interactions precedent instead: SELECT only for the owner, and
-- RPC-only writes, so ownership, position/streak-affecting inserts and
-- append/toggle semantics stay database-authoritative. Two small BEFORE
-- UPDATE triggers (mirroring the existing public.set_updated_at() pattern)
-- keep completed_at / archived_at system-managed and excluded from every
-- grant, so a client can never forge them.

-- ---------------------------------------------------------------------------
-- goals
-- ---------------------------------------------------------------------------

create table public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text not null default '',
  category text,
  status text not null default 'active',
  target_date date,
  progress_percent integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint goals_title_length check (char_length(btrim(title)) between 1 and 120),
  constraint goals_description_length check (char_length(description) <= 3000),
  constraint goals_category_length
    check (category is null or char_length(btrim(category)) between 1 and 60),
  constraint goals_status_allowed
    check (status in ('active', 'paused', 'completed', 'archived')),
  constraint goals_progress_percent_range
    check (progress_percent between 0 and 100),
  -- A completed goal is always shown at 100%; setGoalProgress cannot leave a
  -- completed goal at a partial value, and reopening (status leaves
  -- 'completed') is required before progress can change again. The
  -- apply_goal_completion_status() trigger below is what keeps a legitimate
  -- status change consistent with this check in the same statement.
  constraint goals_completed_progress_full
    check (status <> 'completed' or progress_percent = 100),
  -- Target for the composite foreign key from goal_milestones, the same
  -- pattern connections_id_user_id_key uses for connection_interactions.
  constraint goals_id_user_id_key unique (id, user_id)
);

create table public.goal_milestones (
  id bigint generated by default as identity primary key,
  goal_id bigint not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  position integer not null,
  is_completed boolean not null default false,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint goal_milestones_title_length
    check (char_length(btrim(title)) between 1 and 200),
  constraint goal_milestones_goal_fk
    foreign key (goal_id, user_id)
    references public.goals (id, user_id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- habits
-- ---------------------------------------------------------------------------

create table public.habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  description text not null default '',
  frequency text not null,
  target_per_period integer not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  constraint habits_name_length check (char_length(btrim(name)) between 1 and 120),
  constraint habits_description_length check (char_length(description) <= 1000),
  -- V1 avoids complex custom schedules — daily or weekly only.
  constraint habits_frequency_allowed check (frequency in ('daily', 'weekly')),
  constraint habits_target_per_period_range check (target_per_period between 1 and 100),
  -- Target for the composite foreign key from habit_checkins.
  constraint habits_id_user_id_key unique (id, user_id)
);

create table public.habit_checkins (
  id bigint generated by default as identity primary key,
  habit_id bigint not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  checkin_date date not null,
  value integer not null default 1,
  note text,
  created_at timestamptz not null default now(),
  constraint habit_checkins_value_range check (value between 1 and 1000),
  constraint habit_checkins_note_length check (note is null or char_length(note) <= 500),
  constraint habit_checkins_unique_day unique (habit_id, checkin_date),
  constraint habit_checkins_habit_fk
    foreign key (habit_id, user_id)
    references public.habits (id, user_id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- journal_entries
-- ---------------------------------------------------------------------------

create table public.journal_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text,
  body text not null,
  mood text,
  entry_date date not null default current_date,
  -- Optional cross-links. Plain single-column FKs (not composite) so
  -- ON DELETE SET NULL unlinks cleanly without touching user_id. Same-owner
  -- integrity for all three is enforced by the
  -- enforce_journal_entry_ownership() trigger below, not by the FK itself.
  goal_id bigint references public.goals(id) on delete set null,
  habit_id bigint references public.habits(id) on delete set null,
  prime_assignment_id bigint references public.prime_assignments(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint journal_entries_title_length
    check (title is null or char_length(btrim(title)) between 1 and 200),
  constraint journal_entries_body_length
    check (char_length(body) between 1 and 10000),
  -- Moods are self-reported vocabulary for reflection, never a diagnosis.
  constraint journal_entries_mood_allowed check (
    mood is null or mood in (
      'calm', 'focused', 'energised', 'neutral', 'stressed', 'low',
      'grateful', 'reflective'
    )
  )
);

