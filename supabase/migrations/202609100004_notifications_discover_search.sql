    p.user_id = v_viewer
  from public.posts p
  join public.profiles pr on pr.id = p.user_id and pr.onboarding_completed
  where p.deleted_at is null
    and p.visibility = 'public'
    and not public.blocked_between(v_viewer, p.user_id)
    and (
      p_before_created_at is null
      or (p.created_at, p.id)
         < (p_before_created_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by p.created_at desc, p.id desc
  limit v_limit;
end;
$$;

-- ---------------------------------------------------------------------------
-- Search — people
-- ---------------------------------------------------------------------------
-- Case-insensitive substring match against username / display_name / bio.
-- Same completed / not-self / not-blocked filters as discover_people(). The
-- query length is re-clamped here as defence in depth; the application layer
-- already validates it before calling.

create function public.search_people(
  p_query text,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id uuid,
  username text,
  display_name text,
  bio text,
  viewer_follows boolean,
  total_count bigint
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_query text := btrim(coalesce(p_query, ''));
  v_pattern text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_query) < 2 or char_length(v_query) > 100 then
    return;
  end if;

  v_pattern := '%' || v_query || '%';

  return query
  select
    p.id,
    p.username,
    p.display_name,
    p.bio,
    exists (
      select 1 from public.follows f
      where f.follower_id = v_viewer and f.following_id = p.id
    ),
    count(*) over ()::bigint
  from public.profiles p
  where p.onboarding_completed
    and p.id <> v_viewer
    and not public.blocked_between(v_viewer, p.id)
    and (
      p.username ilike v_pattern
      or p.display_name ilike v_pattern
      or p.bio ilike v_pattern
    )
  order by
    (p.username ilike (v_query || '%')) desc,
    p.username asc
  limit v_limit
  offset v_offset;
end;
$$;

-- ---------------------------------------------------------------------------
-- Search — posts
-- ---------------------------------------------------------------------------
-- Same visibility membership rule as list_feed() (own + public + followed
-- followers-only, block filtered) restricted to a case-insensitive substring
-- match on the body. No external search service, no full-text index for V1 —
-- see docs/NOTIFICATIONS_DISCOVER_SEARCH.md for the documented performance
-- trade-off.

create function public.search_posts(
  p_query text,
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  user_id uuid,
  post_type text,
  body text,
  visibility text,
  created_at timestamptz,
  edited_at timestamptz,
  author_username text,
  author_display_name text,
  like_count integer,
  comment_count integer,
  viewer_liked boolean,
  viewer_bookmarked boolean,
  is_author boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_query text := btrim(coalesce(p_query, ''));
  v_pattern text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_query) < 2 or char_length(v_query) > 100 then
    return;
  end if;

  v_pattern := '%' || v_query || '%';

  return query
  select
    p.id,
    p.user_id,
    p.post_type,
    p.body,
    p.visibility,
    p.created_at,
    p.edited_at,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.post_likes pl where pl.post_id = p.id),
    (select count(*)::integer from public.post_comments pc
      where pc.post_id = p.id and pc.deleted_at is null),
    exists (
      select 1 from public.post_likes pl
      where pl.post_id = p.id and pl.user_id = v_viewer
