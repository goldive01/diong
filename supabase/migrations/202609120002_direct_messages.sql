-- get_or_create_conversation: returns the single direct conversation between
-- the caller and p_other_user_id, creating it if it does not yet exist.
-- Blocked in either direction, a missing/incomplete target, a null target or
-- the caller's own id are all rejected — the same guard shape as
-- follow_user(). Safe under concurrent calls: the unique(user_min_id,
-- user_max_id) constraint is the final authority, not this function's
-- select-then-insert.
create function public.get_or_create_conversation(p_other_user_id uuid)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_min uuid;
  v_max uuid;
  v_conversation_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if p_other_user_id is null or p_other_user_id = v_viewer then
    raise exception using errcode = '22023', message = 'You cannot message this account.';
  end if;

  if not exists (
    select 1 from public.profiles
    where id = p_other_user_id and onboarding_completed
  ) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  if public.blocked_between(v_viewer, p_other_user_id) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  v_min := least(v_viewer, p_other_user_id);
  v_max := greatest(v_viewer, p_other_user_id);

  insert into public.conversations (user_min_id, user_max_id)
  values (v_min, v_max)
  on conflict (user_min_id, user_max_id) do nothing;

  select id into v_conversation_id
  from public.conversations
  where user_min_id = v_min and user_max_id = v_max;

  insert into public.conversation_members (conversation_id, user_id)
  values (v_conversation_id, v_viewer), (v_conversation_id, p_other_user_id)
  on conflict (conversation_id, user_id) do nothing;

  return v_conversation_id;
end;
$$;

-- send_message: the only way a row is ever inserted into public.messages.
-- sender_id is always auth.uid() — never a client-supplied column. Requires
-- live membership and no block between the two participants; stamps the
-- conversation's last_message_at and the sender's own last_read_at (so a
-- sender never sees their own message as unread).
create function public.send_message(p_conversation_id bigint, p_body text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_body text := btrim(coalesce(p_body, ''));
  v_other uuid;
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 5000 then
    raise exception using errcode = '22023', message = 'Write between 1 and 5000 characters.';
  end if;

  if not public.is_conversation_member(p_conversation_id, v_viewer) then
    raise exception using errcode = '42501', message = 'This conversation is not available.';
  end if;

  select cm.user_id into v_other
  from public.conversation_members cm
  where cm.conversation_id = p_conversation_id and cm.user_id <> v_viewer;

  if v_other is not null and public.blocked_between(v_viewer, v_other) then
    raise exception using errcode = '42501', message = 'This conversation is not available.';
  end if;

  insert into public.messages (conversation_id, sender_id, body)
  values (p_conversation_id, v_viewer, v_body)
  returning id into v_new_id;

  update public.conversations
  set last_message_at = now()
  where id = p_conversation_id;

  update public.conversation_members
  set last_read_at = now()
  where conversation_id = p_conversation_id and user_id = v_viewer;

  return v_new_id;
end;
$$;

-- mark_conversation_read: the only way conversation_members.last_read_at
-- changes for a reader. Silently does nothing if the caller is not a member
-- (no row to update) rather than raising, since a page can call this
-- speculatively right after resolving the conversation.
create function public.mark_conversation_read(p_conversation_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  update public.conversation_members
  set last_read_at = now()
  where conversation_id = p_conversation_id and user_id = v_viewer;
end;
$$;

