-- like_post / bookmark_post: idempotent (insert on conflict do nothing). The
-- post must be visible and unblocked. unlike_post / remove_bookmark are plain
-- idempotent deletes.
create function public.like_post(p_post_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
