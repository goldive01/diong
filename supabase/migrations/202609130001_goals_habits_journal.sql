-- goals: owner CRUD, column-scoped INSERT/UPDATE, no DELETE grant at all —
-- goals are archived (status = 'archived'), never hard-deleted. id,
-- created_at, updated_at and completed_at are never client-writable.
grant select on public.goals to authenticated;
grant insert (
  user_id, title, description, category, target_date
) on public.goals to authenticated;
grant update (
  title, description, category, target_date, status, progress_percent
) on public.goals to authenticated;

-- goal_milestones: read-only for clients. Rows are created only by
-- add_goal_milestone() and changed only by toggle_goal_milestone() — no
-- direct INSERT/UPDATE/DELETE grant, matching connection_interactions.
grant select on public.goal_milestones to authenticated;

-- habits: owner CRUD, column-scoped INSERT/UPDATE, no DELETE grant — habits
-- are archived (is_active = false), never hard-deleted. archived_at is
-- trigger-managed and never client-writable.
grant select on public.habits to authenticated;
grant insert (
  user_id, name, description, frequency, target_per_period
) on public.habits to authenticated;
grant update (
  name, description, frequency, target_per_period, is_active
) on public.habits to authenticated;

-- habit_checkins: read-only for clients. Rows are created/updated only by
-- check_in_habit() and removed only by undo_habit_checkin() — matching
-- connection_interactions / goal_milestones.
grant select on public.habit_checkins to authenticated;

-- journal_entries: owner CRUD including DELETE. A journal entry is private,
-- single-owner data with no downstream reference from any other table, so a
-- hard delete (confirmed in the UI) is acceptable here — unlike goals/habits,
