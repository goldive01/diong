-- Diong Direct Messages — Social Network Pass 4.
--
-- Additive only. Adds three tables (public.conversations,
-- public.conversation_members, public.messages), their RLS, two integrity
-- triggers, one internal helper function and the SECURITY DEFINER RPCs that
-- are the only read path for the inbox / conversation / message lists and the
-- only write path for creating a conversation, sending a message and marking
-- a conversation read. It also extends (via ALTER TABLE / CREATE OR REPLACE
-- FUNCTION, never by editing an applied file) the existing
-- public.notifications table from Pass 3 with a new 'new_message'
-- notification type, and adds one AFTER INSERT trigger on the new
-- public.messages table that generates that notification from the
-- send_message() write path (no new client-writable surface). Nothing in
-- this file alters an already-applied migration file, Daily Prime, Prime
-- history / reflections, Connections, the Pass 1 follow / block graph, the
-- Pass 2 post/comment/like/bookmark semantics or the Pass 3 Discover / Search
-- read paths.
--
-- Apply once, in order, after 202609120001_fix_social_profile_username.sql.
-- Depends on public.profiles / auth.users (202607190001),
-- public.follows / public.blocks / public.blocked_between (202609100002 /
-- 202609100003) and public.notifications (202609100004). Each migration is a
-- single transaction and is NOT idempotent — never re-run a migration that
-- already succeeded.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

-- Exactly one direct conversation per user pair: the two participant ids are
-- always stored in canonical (smaller, larger) order, so a
-- unique(user_min_id, user_max_id) index makes a second conversation between
-- the same two accounts impossible regardless of call order — no separate
-- lookup-then-insert race is possible to get wrong.
create table public.conversations (
  id bigint generated by default as identity primary key,
  user_min_id uuid not null references auth.users(id) on delete cascade,
  user_max_id uuid not null references auth.users(id) on delete cascade,
  -- Denormalised for inbox ordering; stamped by send_message(). Null until the
  -- first message is sent — a conversation with no messages yet does not
  -- appear in list_conversations().
  last_message_at timestamptz,
  created_at timestamptz not null default now(),
  constraint conversations_ordered_pair check (user_min_id < user_max_id),
  constraint conversations_unique_pair unique (user_min_id, user_max_id)
);

create table public.conversation_members (
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  -- Everything with created_at at or before this timestamp is read; null means
  -- nothing has ever been read. Updated by send_message() (for the sender) and
  -- mark_conversation_read() (for the reader).
  last_read_at timestamptz,
  created_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create table public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  constraint messages_body_not_empty check (char_length(btrim(body)) between 1 and 5000)
);

create index conversations_last_message_activity_idx
  on public.conversations (last_message_at desc, id desc)
  where last_message_at is not null;

-- The (conversation_id, user_id) primary key serves "who is in conversation X".
-- Add the reverse for "which conversations is user X in" (the inbox query).
create index conversation_members_user_id_idx
  on public.conversation_members (user_id);

create index messages_conversation_created_idx
  on public.messages (conversation_id, created_at desc, id desc);

-- ---------------------------------------------------------------------------
-- Integrity triggers (defence in depth)
-- ---------------------------------------------------------------------------
-- The RPCs below are the only write path in the application, but this trigger
-- keeps the "exactly two members" invariant true no matter how a row is
-- inserted. Diong Pass 4 ships direct messages only — no group chat.

create function public.enforce_conversation_member_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (
    select count(*) from public.conversation_members
    where conversation_id = new.conversation_id
  ) >= 2 then
    raise exception using errcode = '23514',
      message = 'A direct conversation supports exactly two members.';
  end if;
  return new;
end;
$$;

create trigger conversation_members_enforce_limit
before insert on public.conversation_members
for each row execute function public.enforce_conversation_member_limit();

-- ---------------------------------------------------------------------------
-- Internal helper function
-- ---------------------------------------------------------------------------
-- security definer so it can be used inside the RLS policies below without
-- recursion: it reads public.conversation_members as the function owner
-- (bypassing that table's own RLS), exactly the way public.blocked_between()
-- (Pass 2) reads public.blocks as the function owner.

create function public.is_conversation_member(p_conversation_id bigint, p_user_id uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.conversation_members
    where conversation_id = p_conversation_id and user_id = p_user_id
  );
$$;

