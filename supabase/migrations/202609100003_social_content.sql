-- posts: a live post is readable by its author, or by anyone with no block
-- between them and the author when it is public or followers-only-and-followed.
-- Soft-deleted posts are readable by nobody. The feed / detail / list RPCs run
-- as SECURITY DEFINER and re-apply exactly this rule; this policy is the
-- defence-in-depth floor for any direct select.
create policy "Read visible posts"
on public.posts for select
to authenticated
using (
  deleted_at is null
  and (
    user_id = (select auth.uid())
    or (
      not public.blocked_between((select auth.uid()), user_id)
      and (
        visibility = 'public'
        or (
          visibility = 'followers'
          and exists (
            select 1 from public.follows
            where follower_id = (select auth.uid())
              and following_id = posts.user_id
          )
        )
      )
    )
  )
);

-- post_comments: readable when the parent post is visible to the viewer and no
-- block stands between the viewer and the comment author. Deleted comments stay
-- selectable so a thread keeps its shape; the list RPC blanks their body.
create policy "Read comments on visible posts"
on public.post_comments for select
to authenticated
using (
  public.viewer_can_see_post(post_id)
  and not public.blocked_between((select auth.uid()), user_id)
);

-- post_likes / post_bookmarks: a user reads only their own rows. Like counts
-- and "who liked" are never exposed row-by-row; counts come from the RPCs.
-- Bookmarks are private by design.
create policy "Read own likes"
on public.post_likes for select
to authenticated
using (user_id = (select auth.uid()));

create policy "Read own bookmarks"
on public.post_bookmarks for select
to authenticated
using (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Read RPCs — feed, detail, user posts, bookmarks, comments, engagement
-- ---------------------------------------------------------------------------
-- All: language plpgsql / sql, security definer, stable, search_path = '',
-- every object schema-qualified, viewer from auth.uid(), keyset pagination with
-- a hard page cap, engagement counts folded in so callers never issue an
-- N+1 per-post query.

-- Chronological feed: the viewer's own posts, plus public posts and
-- followers-only posts by accounts they follow, newest first, block-filtered.
-- Keyset paginated on (created_at, id).
create function public.list_feed(
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  user_id uuid,
  post_type text,
  body text,
  visibility text,
  created_at timestamptz,
  edited_at timestamptz,
  author_username text,
  author_display_name text,
  like_count integer,
  comment_count integer,
  viewer_liked boolean,
  viewer_bookmarked boolean,
  is_author boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    p.id,
    p.user_id,
    p.post_type,
    p.body,
    p.visibility,
    p.created_at,
    p.edited_at,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.post_likes pl where pl.post_id = p.id),
    (select count(*)::integer from public.post_comments pc
      where pc.post_id = p.id and pc.deleted_at is null),
    exists (
      select 1 from public.post_likes pl
      where pl.post_id = p.id and pl.user_id = v_viewer
    ),
    exists (
      select 1 from public.post_bookmarks pb
      where pb.post_id = p.id and pb.user_id = v_viewer
    ),
    p.user_id = v_viewer
  from public.posts p
  join public.profiles pr on pr.id = p.user_id and pr.onboarding_completed
  where p.deleted_at is null
    and not public.blocked_between(v_viewer, p.user_id)
    and (
      p.user_id = v_viewer
      or p.visibility = 'public'
      or (
        p.visibility = 'followers'
        and exists (
          select 1 from public.follows f
          where f.follower_id = v_viewer and f.following_id = p.user_id
        )
      )
    )
    and (
      p_before_created_at is null
      or (p.created_at, p.id)
         < (p_before_created_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by p.created_at desc, p.id desc
  limit v_limit;
end;
$$;

