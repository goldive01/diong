create table public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  post_type text not null,
  body text not null,
  visibility text not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  constraint posts_body_not_empty check (char_length(btrim(body)) between 1 and 5000),
  constraint posts_type_allowed check (post_type in (
    'update',
    'reflection',
    'progress',
    'learning',
    'achievement',
    'question',
    'resource'
  )),
  constraint posts_visibility_allowed check (visibility in (
    'public',
    'followers',
    'private'
  ))
);

create table public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  -- Referential integrity + the "same post" rule are both enforced by the
  -- composite foreign key post_comments_parent_same_post below.
  parent_comment_id bigint,
  body text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  constraint post_comments_body_not_empty
    check (char_length(btrim(body)) between 1 and 2000),
  -- One reply level only: a comment is either a root (parent null) or a direct
  -- reply to a root. The enforce_comment_one_level trigger below rejects a
  -- reply whose parent is itself a reply, or whose parent is on another post.
  constraint post_comments_id_post_id_key unique (id, post_id),
  constraint post_comments_parent_same_post
    foreign key (parent_comment_id, post_id)
    references public.post_comments (id, post_id) on delete cascade
);

create table public.post_likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  -- One like per user per post. The database is the final authority on
  -- idempotency; the RPCs insert on conflict do nothing.
  primary key (user_id, post_id)
);

create table public.post_bookmarks (
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id bigint not null references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, post_id)
