-- Parses a diong-public-media object path and confirms auth.uid() owns the
-- resource it names, for the three path shapes defined in
-- docs/MEDIA_PROFILE_STORAGE.md:
--   profiles/{userId}/avatar|cover/{uuid}.{ext}                (3 segments)
--   posts/{userId}/{postId}/{uuid}.{ext}                       (3 segments)
--   communities/{ownerUserId}/{communityId}/avatar|cover/{uuid}.{ext} (4 segments)
-- SECURITY DEFINER so it can read public.posts / public.communities as the
-- function owner regardless of the caller's own RLS visibility of those
-- rows — the same reasoning as public.community_role() /
-- public.is_community_banned() reading tables the client cannot select
-- directly. Numeric segments are regex-checked before casting to bigint so a
-- malformed path is rejected (returns false) rather than raising.
create function public.media_path_owner_ok(p_name text)
returns boolean
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_segments text[];
begin
  if v_viewer is null or p_name is null then
    return false;
  end if;

  v_segments := storage.foldername(p_name);

  if v_segments is null or coalesce(array_length(v_segments, 1), 0) = 0 then
    return false;
  end if;

  if v_segments[1] = 'profiles' then
    return array_length(v_segments, 1) = 3
      and v_segments[2] = v_viewer::text
      and v_segments[3] in ('avatar', 'cover');
  end if;

  if v_segments[1] = 'posts' then
    return array_length(v_segments, 1) = 3
      and v_segments[2] = v_viewer::text
      and v_segments[3] ~ '^[0-9]+$'
      and exists (
        select 1 from public.posts
        where id = v_segments[3]::bigint and user_id = v_viewer
      );
  end if;

  if v_segments[1] = 'communities' then
    return array_length(v_segments, 1) = 4
      and v_segments[2] = v_viewer::text
      and v_segments[3] ~ '^[0-9]+$'
      and v_segments[4] in ('avatar', 'cover')
      and exists (
        select 1 from public.communities
        where id = v_segments[3]::bigint and owner_id = v_viewer
      );
  end if;

  return false;
end;
$$;

-- Public read (the bucket is public by design — see the privacy note at the
-- top of this file). Authenticated-only, ownership-checked insert/delete. No
-- update policy: every path segment ends in a freshly generated UUID
-- filename, so an in-place overwrite is never part of the upload flow —
-- replacement always uploads a new object under a new name.
create policy "Public read for diong-public-media"
on storage.objects for select
to public
using (bucket_id = 'diong-public-media');

create policy "Owners can upload to their own diong-public-media path"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'diong-public-media'
  and public.media_path_owner_ok(name)
);

create policy "Owners can delete their own diong-public-media objects"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'diong-public-media'
  and public.media_path_owner_ok(name)
);

