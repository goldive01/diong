drop function public.search_people(text, integer, integer);

create function public.search_people(
  p_query text,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id uuid,
  username text,
  display_name text,
  bio text,
  viewer_follows boolean,
  total_count bigint,
  avatar_path text
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_query text := btrim(coalesce(p_query, ''));
  v_pattern text;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if char_length(v_query) < 2 or char_length(v_query) > 100 then
    return;
  end if;

  v_pattern := '%' || v_query || '%';

  return query
  select
    p.id,
    p.username,
    p.display_name,
    p.bio,
    exists (
      select 1 from public.follows f
      where f.follower_id = v_viewer and f.following_id = p.id
    ),
    count(*) over ()::bigint,
    p.avatar_path
  from public.profiles p
  where p.onboarding_completed
    and p.id <> v_viewer
    and not public.blocked_between(v_viewer, p.id)
    and (
      p.username ilike v_pattern
      or p.display_name ilike v_pattern
      or p.bio ilike v_pattern
    )
  order by
    (p.username ilike (v_query || '%')) desc,
    p.username asc
  limit v_limit
  offset v_offset;
end;
$$;

-- Shared post-media aggregation used by every post-row RPC below: a
-- position-ordered jsonb array, '[]' when the post has no images.
-- (Inlined per call site rather than a helper function, matching the
-- existing repo convention of inlining per-post subqueries such as
-- like_count / comment_count rather than factoring them out.)

-- From 202609100003_social_content.sql. Adds author_avatar_path, media.
drop function public.list_feed(timestamptz, bigint, integer);

create function public.list_feed(
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  user_id uuid,
  post_type text,
  body text,
  visibility text,
  created_at timestamptz,
  edited_at timestamptz,
  author_username text,
  author_display_name text,
  like_count integer,
  comment_count integer,
  viewer_liked boolean,
  viewer_bookmarked boolean,
  is_author boolean,
  author_avatar_path text,
  media jsonb
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    p.id,
    p.user_id,
    p.post_type,
    p.body,
    p.visibility,
    p.created_at,
    p.edited_at,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.post_likes pl where pl.post_id = p.id),
    (select count(*)::integer from public.post_comments pc
      where pc.post_id = p.id and pc.deleted_at is null),
    exists (
      select 1 from public.post_likes pl
      where pl.post_id = p.id and pl.user_id = v_viewer
    ),
    exists (
      select 1 from public.post_bookmarks pb
      where pb.post_id = p.id and pb.user_id = v_viewer
    ),
    p.user_id = v_viewer,
    pr.avatar_path,
    (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', pm.id,
        'storage_path', pm.storage_path,
        'width', pm.width,
        'height', pm.height,
        'position', pm.position,
        'alt_text', pm.alt_text
