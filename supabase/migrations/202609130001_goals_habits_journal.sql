-- Appends a milestone to an owned goal at the next position. Position is
-- always server-computed (max(position) + 1) so the browser can never choose
-- or collide a position.
create function public.add_goal_milestone(p_goal_id bigint, p_title text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_title text := btrim(coalesce(p_title, ''));
  v_position integer;
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.goals where id = p_goal_id and user_id = v_viewer
  ) then
    raise exception using errcode = '42501', message = 'This goal is not available.';
  end if;

  if char_length(v_title) < 1 or char_length(v_title) > 200 then
    raise exception using errcode = '22023', message = 'Choose a title between 1 and 200 characters.';
  end if;

  select coalesce(max(position), 0) + 1 into v_position
  from public.goal_milestones
  where goal_id = p_goal_id;

  insert into public.goal_milestones (goal_id, user_id, title, position)
  values (p_goal_id, v_viewer, v_title, v_position)
  returning id into v_new_id;

  return v_new_id;
end;
$$;

-- Flips a milestone's completion state. Ownership is resolved through the
-- milestone's own goal_id/user_id pair (identical to how the milestone was
-- created), so a milestone can never be toggled by anyone but the goal owner.
create function public.toggle_goal_milestone(p_milestone_id bigint)
returns table (id bigint, is_completed boolean, completed_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_current boolean;
  v_next boolean;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  select m.is_completed into v_current
  from public.goal_milestones m
  where m.id = p_milestone_id and m.user_id = v_viewer;

  if not found then
    raise exception using errcode = '42501', message = 'This milestone is not available.';
  end if;

  v_next := not v_current;

  update public.goal_milestones
  set is_completed = v_next,
      completed_at = case when v_next then now() else null end
  where goal_milestones.id = p_milestone_id;

  return query
  select m.id, m.is_completed, m.completed_at
  from public.goal_milestones m
  where m.id = p_milestone_id;
end;
$$;

-- Records (or updates) today's — or an explicitly dated — check-in for an
-- owned, active habit. Idempotent per (habit_id, checkin_date): calling it
-- again the same day updates value/note rather than erroring, so a user can
-- correct a same-day check-in without an explicit undo first.
create function public.check_in_habit(
  p_habit_id bigint,
  p_checkin_date date default current_date,
  p_value integer default 1,
  p_note text default null
)
returns table (
  id bigint,
  habit_id bigint,
  checkin_date date,
  value integer,
  note text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_date date := coalesce(p_checkin_date, current_date);
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.habits
    where id = p_habit_id and user_id = v_viewer and is_active
  ) then
    raise exception using errcode = '42501', message = 'This habit is not available.';
  end if;

  if v_date > current_date then
    raise exception using errcode = '22023', message = 'Check-in date cannot be in the future.';
  end if;

  if p_value is null or p_value < 1 or p_value > 1000 then
    raise exception using errcode = '22023', message = 'Choose a value between 1 and 1000.';
  end if;

  if v_note is not null and char_length(v_note) > 500 then
    raise exception using errcode = '22023', message = 'Keep the note to 500 characters or fewer.';
  end if;

  insert into public.habit_checkins (habit_id, user_id, checkin_date, value, note)
  values (p_habit_id, v_viewer, v_date, p_value, v_note)
  on conflict (habit_id, checkin_date) do update
    set value = excluded.value, note = excluded.note
  returning habit_checkins.id into v_new_id;

  return query
  select c.id, c.habit_id, c.checkin_date, c.value, c.note
  from public.habit_checkins c
  where c.id = v_new_id;
end;
$$;

-- Removes a check-in for an owned habit. A no-op (not an error) when no
-- check-in exists for that date — undoing something never checked in is
-- harmless, matching leave_community()'s no-op-for-non-member precedent.
create function public.undo_habit_checkin(
  p_habit_id bigint,
  p_checkin_date date default current_date
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.habits where id = p_habit_id and user_id = v_viewer
  ) then
    raise exception using errcode = '42501', message = 'This habit is not available.';
  end if;

  delete from public.habit_checkins
  where habit_id = p_habit_id
    and user_id = v_viewer
    and checkin_date = coalesce(p_checkin_date, current_date);
end;
$$;

