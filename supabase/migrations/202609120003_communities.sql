-- A live community link for one post, or no row when the post is not linked
-- to any (active) community. Purely additive lookup used so a post rendered
-- outside its community's own page (e.g. /posts/[id]) can still show which
-- community it belongs to, without changing the shape of the pre-existing
-- list_feed() / get_post() / list_user_posts() / list_discover_posts() /
-- search_posts() functions from earlier, already-applied migrations.
create function public.get_post_community(p_post_id bigint)
returns table (
  community_id bigint,
  slug text,
  name text
)
language sql
security definer
stable
set search_path = ''
as $$
  select c.id, c.slug, c.name
  from public.community_post_links l
  join public.communities c on c.id = l.community_id
  where l.post_id = p_post_id
    and l.removed_at is null
    and c.is_active;
$$;

