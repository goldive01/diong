create table public.post_media (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null,
  mime_type text not null,
  size_bytes bigint not null,
  width integer,
  height integer,
  position integer not null default 0,
  alt_text text,
  created_at timestamptz not null default now(),
  constraint post_media_mime_type_allowed
    check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  constraint post_media_size_bytes_positive check (size_bytes > 0),
  -- 6291456 = 6 MiB, the V1 post-image cap. Avatar (3 MB) / cover (5 MB)
  -- limits are enforced in the application layer (profiles/communities carry
  -- no size_bytes column), not here.
  constraint post_media_size_bytes_max check (size_bytes <= 6291456),
  constraint post_media_position_non_negative check (position >= 0),
  constraint post_media_alt_text_length
    check (alt_text is null or char_length(alt_text) <= 300),
  constraint post_media_storage_path_not_blank check (char_length(storage_path) > 0),
  constraint post_media_storage_path_unique unique (storage_path),
  -- Also the target of the composite FK used nowhere else, but doubles as the
  -- "at most one row per (post, slot)" invariant that assigns display order.
  constraint post_media_post_position_unique unique (post_id, position)
);

create index post_media_post_position_idx on public.post_media (post_id, position);
create index post_media_user_created_idx on public.post_media (user_id, created_at desc);

-- Defence in depth: attach_post_media() below already checks post ownership
-- before inserting, but this trigger keeps "media.user_id = post's author"
-- true no matter how a row is inserted or updated.
create function public.enforce_post_media_ownership()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.user_id <> (select p.user_id from public.posts p where p.id = new.post_id) then
    raise exception using errcode = '42501',
      message = 'Media must belong to the post author.';
  end if;
  return new;
end;
$$;

create trigger post_media_enforce_ownership
before insert or update on public.post_media
for each row execute function public.enforce_post_media_ownership();

