-- Diong Media + Profile Polish — Pass 7.
--
-- Additive only. Adds:
--   * avatar_path / cover_path columns on public.profiles and public.communities
--   * one new table, public.post_media (0-4 images per post)
--   * one new Storage bucket, diong-public-media, and its storage.objects RLS
--   * one ownership-check trigger and one Storage-path-ownership helper function
--   * four new SECURITY DEFINER RPCs: attach_post_media, remove_post_media,
--     set_community_avatar, set_community_cover
--   * a drop-and-recreate of every existing read RPC that returns a user- or
--     community-identity row, adding an avatar_path (and, for post rows, a
--     media jsonb array) trailing column. Recreated because PostgreSQL does
--     not allow CREATE OR REPLACE FUNCTION to change a function's RETURNS
--     TABLE column list — the argument list of every recreated function is
--     byte-for-byte unchanged, so every existing call site keeps compiling.
--     DROP FUNCTION also drops all privileges on the function (unlike CREATE
--     OR REPLACE), so every recreated function's execute privileges are
--     re-asserted (authenticated only, never anon/public) at the end of this
--     file.
--
-- Nothing in this file alters an existing table's pre-existing columns, an
-- existing migration file, or any pre-existing RLS policy. No previously
-- applied migration is edited.
--
-- Apply once, in order, after 202609130001_goals_habits_journal.sql. Depends
-- on public.profiles / public.posts / public.communities / public.blocks
-- (earlier passes) and public.viewer_can_see_post / public.blocked_between /
-- public.community_role (202609100003 / 202609120003). This migration is a
-- single transaction and is NOT idempotent — never re-run a migration that
-- already succeeded.
--
-- Privacy note, documented again in docs/MEDIA_PROFILE_STORAGE.md: the
-- diong-public-media bucket is PUBLIC READ by design (V1 decision — every
-- object placed here is intentionally social/public media). A public object
-- URL is NOT a privacy boundary: once a client has fetched a direct Storage
-- URL, that URL may remain technically retrievable even after the app UI
-- later hides the associated content (for example, a post image belonging to
-- an author the viewer subsequently blocks). Filenames are unpredictable
-- UUIDs precisely to make this an acceptable V1 trade-off, not a hard
-- guarantee of unlinkability.

