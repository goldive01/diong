-- One community from the viewer's point of view, or no row when missing /
-- inactive. Resolves the viewer's role (null when not a member) and a live
-- member count.
create function public.get_community(p_slug text)
returns table (
  id bigint,
  slug text,
  name text,
  description text,
  rules text,
  owner_id uuid,
  owner_username text,
  owner_display_name text,
  member_count integer,
  created_at timestamptz,
  viewer_role text
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    c.id,
    c.slug,
    c.name,
    c.description,
    c.rules,
    c.owner_id,
    pr.username,
    pr.display_name,
    (select count(*)::integer from public.community_members m where m.community_id = c.id),
    c.created_at,
    public.community_role(c.id, v_viewer)
  from public.communities c
  join public.profiles pr on pr.id = c.owner_id
  where c.slug = lower(btrim(coalesce(p_slug, '')))
    and c.is_active;
end;
$$;

-- Communities the viewer has joined (any role), alphabetical by name — a
-- deterministic order with id as the final tie-break, offset paginated.
create function public.list_my_communities(
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id bigint,
  slug text,
  name text,
  description text,
  member_count integer,
  viewer_role text,
  total_count bigint
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    c.id,
    c.slug,
    c.name,
    c.description,
    (select count(*)::integer from public.community_members m2 where m2.community_id = c.id),
    cm.role,
    count(*) over ()
  from public.community_members cm
  join public.communities c on c.id = cm.community_id and c.is_active
  where cm.user_id = v_viewer
  order by c.name asc, c.id asc
  limit v_limit offset v_offset;
end;
$$;

