      select count(*)::integer
      from public.user_interests vi
      join public.user_interests ci
        on ci.interest_id = vi.interest_id and ci.user_id = p.id
      where vi.user_id = v_viewer
    ) desc,
    p.created_at desc,
    p.id asc
