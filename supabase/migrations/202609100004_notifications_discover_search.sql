      select 1 from public.post_bookmarks pb
      where pb.post_id = p.id and pb.user_id = v_viewer
    ),
    p.user_id = v_viewer
  from public.posts p
  join public.profiles pr on pr.id = p.user_id
  where p.deleted_at is null
    and p.body ilike v_pattern
    and not public.blocked_between(v_viewer, p.user_id)
    and (
      p.user_id = v_viewer
      or p.visibility = 'public'
      or (
        p.visibility = 'followers'
        and exists (
          select 1 from public.follows f
          where f.follower_id = v_viewer and f.following_id = p.user_id
        )
      )
    )
    and (
