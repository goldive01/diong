-- Comments for one visible post: top-level comments and their single reply
-- level, oldest first, block-filtered. A deleted top-level comment is returned
-- as a tombstone (body null, is_deleted true) only when it still has a live
-- reply, so a reply keeps its context; deleted replies are dropped. Capped at
-- 500 rows for Pass 2.
create function public.list_post_comments(p_post_id bigint)
returns table (
  id bigint,
  parent_comment_id bigint,
  user_id uuid,
  author_username text,
  author_display_name text,
  body text,
  created_at timestamptz,
  edited_at timestamptz,
  is_deleted boolean,
  is_author boolean
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not public.viewer_can_see_post(p_post_id) then
    return;
  end if;

  return query
  select
    c.id,
    c.parent_comment_id,
    c.user_id,
    pr.username,
    pr.display_name,
    case when c.deleted_at is null then c.body else null end,
    c.created_at,
    c.edited_at,
    c.deleted_at is not null,
    c.user_id = v_viewer
  from public.post_comments c
  join public.profiles pr on pr.id = c.user_id
  where c.post_id = p_post_id
    and not public.blocked_between(v_viewer, c.user_id)
    and (
      c.deleted_at is null
      or (
        c.parent_comment_id is null
        and exists (
          select 1 from public.post_comments r
          where r.parent_comment_id = c.id and r.deleted_at is null
        )
      )
    )
  order by
    coalesce(c.parent_comment_id, c.id),
    (c.parent_comment_id is not null),
    c.created_at,
    c.id
  limit 500;
end;
$$;

-- ---------------------------------------------------------------------------
-- Mutation RPCs — the only write path for posts, comments, likes, bookmarks
-- ---------------------------------------------------------------------------

create function public.create_post(
  p_post_type text,
  p_body text,
  p_visibility text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_body text := btrim(coalesce(p_body, ''));
  v_new_id bigint;
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if not exists (
    select 1 from public.profiles where id = v_viewer and onboarding_completed
  ) then
    raise exception using errcode = '42501', message = 'This account is not available.';
  end if;

  if p_post_type is null or p_post_type not in (
    'update', 'reflection', 'progress', 'learning', 'achievement', 'question', 'resource'
  ) then
    raise exception using errcode = '22023', message = 'Choose a valid post type.';
  end if;

  if p_visibility is null or p_visibility not in ('public', 'followers', 'private') then
    raise exception using errcode = '22023', message = 'Choose a valid visibility.';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 5000 then
    raise exception using errcode = '22023', message = 'Write between 1 and 5000 characters.';
  end if;

  insert into public.posts (user_id, post_type, body, visibility)
  values (v_viewer, p_post_type, v_body, p_visibility)
  returning id into v_new_id;

  return v_new_id;
end;
$$;

-- Edit the body and/or visibility of the caller's own live post. id, user_id,
-- post_type and created_at can never change here. edited_at is stamped.
create function public.update_post(
  p_post_id bigint,
  p_body text,
  p_visibility text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_body text := btrim(coalesce(p_body, ''));
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  if p_visibility is null or p_visibility not in ('public', 'followers', 'private') then
    raise exception using errcode = '22023', message = 'Choose a valid visibility.';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 5000 then
    raise exception using errcode = '22023', message = 'Write between 1 and 5000 characters.';
  end if;

  update public.posts
  set body = v_body,
      visibility = p_visibility,
      edited_at = now()
  where id = p_post_id
    and user_id = v_viewer
    and deleted_at is null;

  if not found then
    raise exception using errcode = '42501', message = 'This post is not available.';
  end if;
end;
$$;

