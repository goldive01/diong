    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    c.id,
    pr.id,
    pr.username,
    pr.display_name,
    lm.body,
    c.last_message_at,
    (
      lm.created_at is not null
      and lm.sender_id <> v_viewer
      and lm.created_at > coalesce(cm.last_read_at, '-infinity'::timestamptz)
    ),
    pr.avatar_path
  from public.conversation_members cm
  join public.conversations c on c.id = cm.conversation_id
  join public.conversation_members other_cm
    on other_cm.conversation_id = c.id and other_cm.user_id <> v_viewer
  join public.profiles pr on pr.id = other_cm.user_id
  left join lateral (
    select m.body, m.created_at, m.sender_id
    from public.messages m
    where m.conversation_id = c.id
    order by m.created_at desc, m.id desc
    limit 1
  ) lm on true
  where cm.user_id = v_viewer
    and c.last_message_at is not null
    and not public.blocked_between(v_viewer, other_cm.user_id)
    and (
      p_before_last_message_at is null
      or (c.last_message_at, c.id)
         < (p_before_last_message_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by c.last_message_at desc, c.id desc
  limit v_limit;
end;
$$;

