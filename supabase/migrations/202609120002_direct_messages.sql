-- Dedup policy: unlike a like/follow (idempotent toggle) or a comment (each a
-- distinct real event, never deduplicated), a message thread can produce many
-- events in quick succession. To avoid one notification per chat message, the
-- recipient gets at most one UNREAD 'new_message' notification per
-- conversation at a time — a further message from the same conversation
-- while that notification is still unread does not create a second one; once
-- the recipient reads it (mark_notification_read / mark_all_notifications_read),
-- the next new message creates a fresh one. This is deterministic and needs
-- no time-window heuristic, the same shape of reasoning Pass 3 documented for
-- follow / like dedup.
create function public.notify_new_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_recipient uuid;
begin
  select cm.user_id into v_recipient
  from public.conversation_members cm
  where cm.conversation_id = new.conversation_id
    and cm.user_id <> new.sender_id
  limit 1;

  if v_recipient is null then
    return new;
  end if;

  if not exists (
    select 1 from public.notifications
    where user_id = v_recipient
      and actor_user_id = new.sender_id
      and notification_type = 'new_message'
      and entity_id = new.conversation_id
      and read_at is null
  ) then
    insert into public.notifications
      (user_id, actor_user_id, notification_type, entity_type, entity_id)
    values
      (v_recipient, new.sender_id, 'new_message', 'conversation', new.conversation_id);
  end if;

  return new;
end;
$$;

create trigger messages_notify_new_message
after insert on public.messages
for each row execute function public.notify_new_message();

-- list_notifications() (Pass 3) resolves a per-row "is the target still
-- navigable" flag. Re-created here (same signature, same nine columns) only
-- to add the 'new_message' branch to that resolution — membership + no block,
-- via is_conversation_member(), which did not exist when Pass 3 was written.
-- Every other branch is copied unchanged from 202609100004_notifications_
-- discover_search.sql.
create or replace function public.list_notifications(
  p_before_created_at timestamptz default null,
  p_before_id bigint default null,
  p_limit integer default 20
)
returns table (
  id bigint,
  notification_type text,
  entity_type text,
  entity_id bigint,
  actor_user_id uuid,
  actor_username text,
  actor_display_name text,
  target_post_id bigint,
  target_available boolean,
  read_at timestamptz,
  created_at timestamptz
)
language plpgsql
security definer
stable
set search_path = ''
as $$
declare
  v_viewer uuid := auth.uid();
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 20);
begin
  if v_viewer is null then
    raise exception using errcode = '42501', message = 'Authentication is required.';
  end if;

  return query
  select
    n.id,
    n.notification_type,
    n.entity_type,
    n.entity_id,
    n.actor_user_id,
    pr.username,
    pr.display_name,
    case
      when n.notification_type in ('post_like', 'post_comment')
        then case when public.viewer_can_see_post(n.entity_id) then n.entity_id else null end
      when n.notification_type = 'comment_reply'
        then case
          when c.deleted_at is null and public.viewer_can_see_post(c.post_id)
            then c.post_id
          else null
        end
      else null
    end,
    case
      when n.notification_type = 'new_follower' then
        exists (
          select 1 from public.profiles p
          where p.id = n.actor_user_id and p.onboarding_completed
        )
      when n.notification_type in ('post_like', 'post_comment') then
        public.viewer_can_see_post(n.entity_id)
      when n.notification_type = 'comment_reply' then
        c.deleted_at is null and public.viewer_can_see_post(c.post_id)
      when n.notification_type = 'new_message' then
        public.is_conversation_member(n.entity_id, v_viewer)
      else false
    end,
    n.read_at,
    n.created_at
  from public.notifications n
  left join public.profiles pr on pr.id = n.actor_user_id
  left join public.post_comments c
    on n.notification_type = 'comment_reply' and c.id = n.entity_id
  where n.user_id = v_viewer
    and (
      n.actor_user_id is null
      or not public.blocked_between(v_viewer, n.actor_user_id)
    )
    and (
      p_before_created_at is null
      or (n.created_at, n.id)
         < (p_before_created_at, coalesce(p_before_id, 9223372036854775807))
    )
  order by n.created_at desc, n.id desc
  limit v_limit;
end;
$$;

